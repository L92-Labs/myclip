#!/usr/bin/env python3
"""Collect verbatim licenses from the pinned runtime modules for every target."""
import argparse
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def generate():
    modules = {}
    for platform in ("linux/amd64", "linux/arm64", "darwin/amd64", "darwin/arm64"):
        system, arch = platform.split("/")
        env = dict(os.environ, GOOS=system, GOARCH=arch, CGO_ENABLED="0")
        output = subprocess.check_output([
            "go", "list", "-deps", "-f",
            "{{if .Module}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}", ".",
        ], cwd=ROOT, env=env, text=True)
        for line in output.splitlines():
            parts = line.split("\t")
            if len(parts) == 3 and parts[1]:
                name, version, directory = parts
                modules[name] = (version, Path(directory))
    sections = ["THIRD-PARTY NOTICES\n\nGenerated by scripts/licenses.py from pinned runtime dependencies.\n"
                "Notices may cover additional components of those modules.\n"]

    def include(title, path):
        sections.append("\n" + "=" * 72 + "\n" + title + "\n" + "=" * 72 + "\n\n" + path.read_text().rstrip() + "\n")

    goroot = Path(subprocess.check_output(["go", "env", "GOROOT"], cwd=ROOT, text=True).strip())
    include("Go runtime and standard library — https://go.dev/LICENSE", goroot / "LICENSE")
    for name, (version, directory) in sorted(modules.items()):
        paths = sorted(p for p in directory.rglob("*") if p.is_file() and
                       p.name.upper().split(".")[0] in {"LICENSE", "COPYING", "NOTICE"})
        if not paths:
            raise RuntimeError("No license found for " + name)
        for path in paths:
            include(f"{name} {version} — {path.relative_to(directory)}", path)
        if name == "golang.org/x/image":
            include(f"Go fonts ({name} {version})", directory / "font/gofont/ttfs/README")
    include("Lucide icons — https://lucide.dev/license", ROOT / "licenses/Lucide.txt")
    sections.append("\nSQLite — https://sqlite.org/copyright.html\n\n"
                    "SQLite is in the public domain. The bundled MyGo SQLite wrapper is covered by the MyGo notices above.\n")
    return "".join(sections)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in notices differ")
    args = parser.parse_args()
    target = ROOT / "THIRD_PARTY_NOTICES.txt"
    content = generate()
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit("Notices are stale; run python3 scripts/licenses.py")
        print("PASS: third-party notices match pinned runtime dependencies")
    else:
        target.write_text(content)
        print("Generated THIRD_PARTY_NOTICES.txt")
